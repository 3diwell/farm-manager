def _norm(name):
    return re.sub(r"[-_.]+", "-", str(name or "")).lower()


# ── маркеры зависимостей (PEP 508), минимально и без пакета packaging ─────────────────────────

_TOK = re.compile(r"\s*(\(|\)|'[^']*'|\"[^\"]*\"|===|==|!=|<=|>=|~=|<|>|not\s+in\b|in\b|and\b|or\b|"
                  r"[A-Za-z_][A-Za-z0-9_.]*)")
_VERSION_VARS = ("python_version", "python_full_version", "implementation_version")


def marker_env():
    """Окружение сборки: Windows, CPython, та версия Python, которой запущен скрипт."""
    v = sys.version_info
    return {"sys_platform": "win32", "platform_system": "Windows", "os_name": "nt",
            "platform_machine": platform.machine() or "AMD64",
            "implementation_name": "cpython", "platform_python_implementation": "CPython",
            "python_version": "%d.%d" % (v[0], v[1]),
            "python_full_version": "%d.%d.%d" % (v[0], v[1], v[2]),
            "implementation_version": "%d.%d.%d" % (v[0], v[1], v[2])}


def _vt(s):
    return tuple(int(x) for x in re.findall(r"\d+", str(s)))


def _cmp(lhs, op, rhs, lvar, rvar):
    if lvar in _VERSION_VARS or rvar in _VERSION_VARS:
        a, b = _vt(lhs), _vt(rhs)
        if op == "~=":
            return a >= b and a[:max(1, len(b) - 1)] == b[:max(1, len(b) - 1)]
    else:
        a, b = str(lhs), str(rhs)
        if op == "~=":
            return a == b
    op = re.sub(r"\s+", " ", op)
    return {"==": a == b, "===": a == b, "!=": a != b, "<": a < b, "<=": a <= b, ">": a > b,
            ">=": a >= b, "in": str(lhs) in str(rhs), "not in": str(lhs) not in str(rhs)}.get(op, True)


def marker_true(marker, extras=(), env=None):
    """Выполняется ли маркер зависимости («; extra == 'standard' and sys_platform == 'win32'»)
    для окружения сборки и запрошенных extras. Кавычки любые. Непонятное считается выполненным:
    лишний текст лицензии лучше пропущенного."""
    env = dict(env or marker_env())
    toks = _TOK.findall(marker or "")
    if "".join(toks).replace(" ", "") != re.sub(r"\s+", "", marker or ""):
        return True
    pos = [0]

    def peek():
        return toks[pos[0]] if pos[0] < len(toks) else None

    def take():
        pos[0] += 1
        return toks[pos[0] - 1]

    def value():
        t = take()
        if t is None:
            raise ValueError("маркер оборван")
        if t[0] in "'\"":
            return t[1:-1], None
        return env.get(t, ""), t

    def atom():
        if peek() == "(":
            take()
            r = expr()
            if take() != ")":
                raise ValueError("скобка")
            return r
        (lv, lvar), op, (rv, rvar) = value(), take(), value()
        if lvar == "extra" or rvar == "extra":
            want = _norm(rv if lvar == "extra" else lv)
            hit = want in set(_norm(e) for e in extras)
            return hit if op == "==" else (not hit if op == "!=" else True)
        return _cmp(lv, op, rv, lvar, rvar)

    def conj():
        r = atom()
        while peek() == "and":
            take()
            r = atom() and r
        return r

    def expr():
        r = conj()
        while peek() == "or":
            take()
            r = conj() or r
        return r

    try:
        out = expr()
        return out if pos[0] == len(toks) else True
    except Exception:
        return True


def split_requirement(req):
    """«uvicorn[standard]>=0.30 ; extra == "x"» -> ("uvicorn", {"standard"}, 'extra == "x"')."""
    req, _, marker = str(req).partition(";")
    m = re.match(r"\s*([A-Za-z0-9][A-Za-z0-9._-]*)\s*(?:\[([^\]]*)\])?", req)
    if not m:
        return None, set(), marker.strip()
    extras = set(e.strip() for e in (m.group(2) or "").split(",") if e.strip())
    return m.group(1), extras, marker.strip()


def requirement_roots():
    out = []
    with io.open(os.path.join(REPO, "requirements.txt"), encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                out.append(line)
    return out


def closure(roots, env=None):
    """Пакеты и всё, что они тянут за собой, с учётом extras ТОЛЬКО там, где они запрошены."""
    done, order, stack = {}, [], [split_requirement(r)[:2] for r in roots]
    missing = set()
    while stack:
        name, extras = stack.pop(0)
        if not name:
            continue
        key = _norm(name)
        prev = done.get(key)
        if prev is not None and extras <= prev:
            continue
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            missing.add(key)
            done[key] = set(extras)
            continue
        if prev is None:
            order.append(dist)
        done[key] = set(extras) | (prev or set())
        for req in dist.requires or []:
            dep, dep_extras, marker = split_requirement(req)
            if dep and (not marker or marker_true(marker, done[key], env)):
                stack.append((dep, dep_extras))
    return order, sorted(missing)


# ── состав EXE ────────────────────────────────────────────────────────────────────────────────

def _repo_tops(pd=None):
    """Собственные имена проекта в EXE (server, app, web, …) — не сторонние пакеты.

    Свои: модули *.py/*.pyw в корне, папки-пакеты Python (с __init__.py) и папки данных (web,
    printer_covers, …). Папка данных, чьё имя совпадает с модулем УСТАНОВЛЕННОГО пакета, своей не
    считается: папка packaging/ проекта — не пакет Python, а одноимённый пакет PyPI «packaging»
    вшит во все EXE, и его лицензию обязаны приложить (замечание проверки R-130, 29.09.2026)."""
    if pd is None:
        pd = md.packages_distributions()
    tops = set()
    for n in os.listdir(REPO):
        base, ext = os.path.splitext(n)
        path = os.path.join(REPO, n)
        if ext in (".py", ".pyw") and os.path.isfile(path):
            tops.add(base)
        elif os.path.isdir(path) and not n.startswith((".", "__")):
            if os.path.isfile(os.path.join(path, "__init__.py")) or n not in pd:
                tops.add(n)
    return tops


def exe_contents(exe):
    """(модули верхнего уровня, [(имя, версия) из *.dist-info в корне архива])."""
    try:
        from PyInstaller.archive.readers import CArchiveReader
    except Exception as e:
        raise SystemExit("PyInstaller не импортируется этим интерпретатором (%s): %s" % (sys.executable, e))
    arc = CArchiveReader(exe)
    names = [n.replace("\\", "/") for n in arc.toc]
    mods = set()
    for n in arc.toc:
        if n.lower().endswith(".pyz"):
            mods |= set(arc.open_embedded_archive(n).toc.keys())
    tops = set(m.split(".")[0] for m in mods)
    tops |= set(n.split("/")[0] for n in names if "/" in n)
    tops |= set(re.sub(r"\..*$", "", n) for n in names if "/" not in n and n.lower().endswith(".pyd"))
    infos = set()
    for n in names:
        first = n.split("/")[0]
        m = re.match(r"(.+)-([^-]+)\.dist-info$", first)
        if m and "/" in n:
            infos.add((m.group(1), m.group(2)))
    return tops, sorted(infos)


def dists_in_exes(exes):
    pd = md.packages_distributions()
    own = _repo_tops(pd)
    found, problems = {}, []
    for exe in exes:
        tops, infos = exe_contents(exe)
        for t in sorted(tops - own):
            if t.startswith("__"):
                continue            # __pycache__, __main__ и т. п. — не имена пакетов
            for dn in pd.get(t, ()):
                found.setdefault(_norm(dn), dn)
        for dn, ver in infos:
            try:
                have = md.version(dn)
            except md.PackageNotFoundError:
                problems.append("%s %s есть в %s, но не установлен в этом окружении"
                                % (dn, ver, os.path.basename(exe)))
                continue
            if have != ver:
                problems.append("%s: в %s версия %s, установлена %s" % (dn, os.path.basename(exe), ver, have))
            found.setdefault(_norm(dn), dn)
    if problems:
        raise SystemExit("EXE собран не этим окружением (%s):\n  %s\nЗапустите сборщик тем интерпретатором, "
                         "которым собирался EXE." % (sys.executable, "\n  ".join(problems)))
    return [md.distribution(n) for _, n in sorted(found.items())]


# ── тексты ────────────────────────────────────────────────────────────────────────────────────

def _clean(text):
    text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\x00", "")
    return "\n".join(line.rstrip() for line in text.split("\n")).strip()


def license_texts(dist):
    texts = []
    for f in dist.files or []:
        p = str(f).replace("\\", "/")
        if ".dist-info/" in p and LICENSE_NAME.search(p):
            try:
                with io.open(str(f.locate()), encoding="utf-8", errors="replace") as fh:
                    texts.append((p.split(".dist-info/", 1)[1], _clean(fh.read())))
            except Exception:
                continue
    return sorted(texts)


def package_entry(dist):
    meta = dist.metadata
    lic = meta.get("License-Expression") or meta.get("License") or ""
    home = meta.get("Home-page") or ""
    if not home:
        for u in meta.get_all("Project-URL") or []:
            home = u.split(",", 1)[-1].strip()
            break
    return {"name": meta["Name"], "version": dist.version,
            "license": (lic.splitlines() or [""])[0].strip()[:120],
            "home": home, "texts": license_texts(dist)}


def make_part(dists, source, missing=()):
    return {"python": "%d.%d.%d" % sys.version_info[:3], "source": source,
            "missing": list(missing), "packages": [package_entry(d) for d in dists]}


def in_repo_sections():
    parts = []
    for title, rel, how in IN_REPO:
        p = os.path.join(REPO, *rel.split("/"))
        if not os.path.isfile(p):
            continue
        with io.open(p, encoding="utf-8", errors="replace") as f:
            txt = f.read(4000) if how == "head" else f.read()
        if how == "head":
            m = re.search(r"/\*[!*]?(.*?)\*/", txt, re.S)
            txt = m.group(1).strip() if m else txt[:600]
        parts.append(RULE + "\n%s\n" % title + RULE + "\n" + _clean(txt) + "\n")
    return parts


def package_sections(packages):
    """Пакеты из всех частей: один раз каждая пара «имя, версия», по алфавиту."""
    uniq = {}
    for p in packages:
        uniq.setdefault((_norm(p["name"]), p["version"]), p)
    parts = []
    for key in sorted(uniq, key=lambda k: (k[0], [int(x) if x.isdigit() else x for x in re.split(r"(\d+)", k[1])])):
        p = uniq[key]
        head = "%s %s — %s" % (p["name"], p["version"], p["license"] or "лицензия не указана в описании пакета")
        body = "\n\n".join("--- %s ---\n%s" % (n, t) for n, t in p["texts"]) or \
               "(текст лицензии в пакете не найден; см. %s)" % (p.get("home") or "описание пакета")
        parts.append(RULE + "\n" + head + "\n" + RULE + "\n" + body + "\n")
    return parts


def assemble(parts, header=True):
    pkgs = [p for part in parts for p in part.get("packages", [])]
    chunks = ([HEADER] + in_repo_sections() if header else []) + package_sections(pkgs)
    return "\n".join(chunks)


def _headings(text):
    lines = text.split("\n")
    return [lines[i + 1] for i in range(len(lines) - 2) if lines[i] == RULE and lines[i + 2] == RULE]


def check_file(path, text):
    """0 — файл совпадает со сборкой; 1 — нет (печатает, чем именно отличается)."""
    try:
        with io.open(path, encoding="utf-8", newline="") as f:
            have = f.read().replace("\r\n", "\n")
    except FileNotFoundError:
        print("НЕТ ФАЙЛА: %s" % path)
        return 1
    if have == text:
        print("совпадает: %s" % path)
        return 0
    a, b = _headings(have), _headings(text)
    print("НЕ СОВПАДАЕТ: %s" % path)
    for ln in difflib.unified_diff(a, b, "в файле", "в сборке", lineterm="", n=0):
        if not ln.startswith(("@@", "---", "+++")):
            print("  " + ln)
    if a == b:
        print("  состав тот же, отличаются тексты лицензий")
    return 1


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--from-exe", nargs="+", default=None, help="состав — из этих EXE")
    ap.add_argument("--roots", nargs="*", default=None, help="состав — по зависимостям этих пакетов")
    ap.add_argument("--part-out", default=None, help="записать часть (JSON) для --assemble")
    ap.add_argument("--assemble", nargs="+", default=None, help="собрать файл из частей (JSON)")
    ap.add_argument("--out", default=None)
    ap.add_argument("--check", default=None, help="сверить готовый файл со сборкой; 1 — устарел")
    ap.add_argument("--append", action="store_true", help="без шапки и файлов репозитория (дописать)")
    a = ap.parse_args(argv)

    if a.assemble:
        parts = []
        for p in a.assemble:
            with io.open(p, encoding="utf-8") as f:
                parts.append(json.load(f))
    else:
        if a.from_exe:
            part = make_part(dists_in_exes(a.from_exe), "exe")
        else:
            dists, missing = closure(a.roots if a.roots else requirement_roots())
            part = make_part(dists, "roots", missing)
        print("пакетов: %d, не установлены: %s" % (len(part["packages"]), ", ".join(part["missing"]) or "нет"))
        if a.part_out:
            with io.open(a.part_out, "w", encoding="utf-8", newline="\n") as f:
                json.dump(part, f, ensure_ascii=False, indent=1, sort_keys=True)
            print("часть записана: %s" % a.part_out)
        parts = [part]
    if not (a.out or a.check):
        return 0 if (a.part_out or not a.assemble) else 2
    text = assemble(parts, header=not a.append)
    if a.check:
        return check_file(a.check, text)
    mode = "a" if a.append else "w"
    with io.open(a.out, mode, encoding="utf-8", newline="\r\n") as f:
        f.write(("\n" if a.append else "") + text)
    print("записано: %s" % a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
