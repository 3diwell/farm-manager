def call(fn, *a, **k):
    """Вызов, который на старом коде может упасть (нет функции/параметра): исключение -> текст,
    проверка тогда краснеет, а набор доходит до конца."""
    try:
        return fn(*a, **k)
    except Exception as e:
        return "EXC: %r" % (e,)


