def mk_3mf_ids(used, project):
    """3mf с произвольными номерами филаментов в slice_info (в том числе невозможными)."""
    si = ['<?xml version="1.0" encoding="UTF-8"?>', "<config>", "  <plate>", '    <metadata key="index" value="1"/>']
    for fid in sorted(used):
        si.append('    <filament id="%d" type="PLA" color="#FFFFFF" used_m="1.00" used_g="%.2f" />' % (fid, used[fid]))
    si += ["  </plate>", "</config>"]
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("3D/3dmodel.model", "<model/>")
        z.writestr("Metadata/project_settings.config", json.dumps({"filament_type": list(project)}))
        z.writestr("Metadata/plate_1.gcode", gcode_bambu(used, project))
        z.writestr("Metadata/slice_info.config", "\n".join(si).encode("utf-8"))
    return buf.getvalue()


