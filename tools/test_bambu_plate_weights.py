def filament(material, color="Белый"):
    fid = be.core.new_id("fil_")
    with be.lock_inv:
        be.conn_inv.execute("INSERT INTO inv_filaments (id, material, color_name, color_hex) VALUES (?,?,?,?)",
                            (fid, material, color, "#FFFFFF"))
        be.conn_inv.commit()
    return fid


def spool(material, remaining, pid="", slot=-1, total=1000.0):
    sid = be.core.new_id("spool_")
    with be.lock_inv:
        be.conn_inv.execute(
            "INSERT INTO inv_spools (id, filament_id, weight_total_g, weight_remaining_g, status, ams_printer_id, ams_slot) "
            "VALUES (?,?,?,?,?,?,?)", (sid, filament(material), total, remaining, "loaded" if pid else "in_stock", pid, slot))
        be.conn_inv.commit()
    return sid


def rem(sid):
    with be.lock_inv:
        r = be.conn_inv.execute("SELECT weight_remaining_g FROM inv_spools WHERE id=?", (sid,)).fetchone()
    return round(float(r["weight_remaining_g"]), 2) if r else None


def pos(sid):
    with be.lock_inv:
        r = be.conn_inv.execute("SELECT ams_printer_id, ams_slot FROM inv_spools WHERE id=?", (sid,)).fetchone()
    return (r["ams_printer_id"], int(r["ams_slot"])) if r else None


def pending_rows(pid):
    with be.lock_inv:
        return [dict(r) for r in be.conn_inv.execute(
            "SELECT * FROM inv_pending_prints WHERE printer_id=? ORDER BY rowid", (pid,)).fetchall()]


def ov_slots(pid):
    for p in be.inv_ams_overview().get("printers", []):
        if p.get("printer_id") == pid:
            return {s["index"]: s for s in p.get("slots", [])}
    return {}


