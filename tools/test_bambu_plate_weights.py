PROJECT = ("PLA", "PETG", "PLA", "ABS")


def gcode_bambu(used, project=PROJECT):
    """Шапка plate_N.gcode, как у Bambu Studio: вес только использованных филаментов, по номеру."""
    w = ",".join("%.2f" % used[k] for k in sorted(used))
    return ("; HEADER_BLOCK_START\n; generated by BambuStudio 01.09.07.52\n; total layer number: 40\n"
            "; total filament length [mm] : 4123.45\n; total filament volume [cm^3] : 9876.54\n"
            "; total filament weight [g] : " + w + "\n"
            "; filament_density: " + ",".join("1.24" for _ in project) + "\n"
            "; HEADER_BLOCK_END\n; CONFIG_BLOCK_START\n; filament_type = " + ";".join(project) + "\n"
            "; CONFIG_BLOCK_END\nG28\nG1 X10 Y10\n").encode("utf-8")


def slice_info(plates, with_used_g=True, project=PROJECT):
    out = ['<?xml version="1.0" encoding="UTF-8"?>', "<config>", "  <header>",
           '    <header_item key="X-BBL-Client-Type" value="slicer"/>', "  </header>"]
    for num, used in plates.items():
        out.append("  <plate>")
        out.append('    <metadata key="index" value="%d"/>' % num)
        for fid in sorted(used):
            extra = (' used_g="%.2f"' % used[fid]) if with_used_g else ""
            out.append('    <filament id="%d" tray_info_idx="GF" type="%s" color="#FFFFFF" used_m="4.12"%s />'
                       % (fid, project[fid - 1], extra))
        out.append("  </plate>")
    out.append("</config>")
    return "\n".join(out).encode("utf-8")


def mk_3mf(plates, with_slice_info=True, with_used_g=True, project=PROJECT):
    """plates: {номер плиты: {номер филамента: граммы}}."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("3D/3dmodel.model", "<model/>")
        z.writestr("Metadata/project_settings.config",
                   json.dumps({"filament_type": list(project), "filament_colour": ["#FFFFFF"] * len(project)}))
        for num, used in plates.items():
            z.writestr("Metadata/plate_%d.gcode" % num, gcode_bambu(used, project))
        if with_slice_info:
            z.writestr("Metadata/slice_info.config", slice_info(plates, with_used_g, project))
    return buf.getvalue()


