def make_big(mb=60, nl=b"\n"):
    head = nl.join([b"; HEADER_BLOCK_START", b"; generated by Creality Print V6.3.1", b"; HEADER_BLOCK_END", b"",
                    b"START_PRINT EXTRUDER_TEMP=250 BED_TEMP=70", b"T1", b"M104 S250"]) + nl
    rnd = random.Random(7)
    tpl = [b"G1 X%.3f Y%.3f E%.5f", b";TYPE:Outer wall", b"; layer num/total_layer_count: 5/100",
           b"G0 F12000 X%.3f Y%.3f", b";WIDTH:0.42", b"; FEATURE: Inner wall", b"M73 P12 R40"]
    chunk = []
    for i in range(20000):
        t = tpl[i % len(tpl)]
        chunk.append(t % tuple(rnd.random() * 200 for _ in range(t.count(b"%"))) if b"%" in t else t)
    chunk = nl.join(chunk) + nl
    tail = nl.join([b"; filament used [mm] = 0.00, 1197.41", b"; filament used [cm3] = 0.00, 2.88",
                    b"; filament used [g] = 0.00, 3.66", b"; filament cost = 0.00, 0.05", b"; CONFIG_BLOCK_START",
                    b"; default_filament_colour = ;#BEEB61", b"; default_filament_type = ;PETG",
                    b"; filament_colour = #9ea7ae;#BEEB61", b"; filament_type = PLA;PETG", b"; CONFIG_BLOCK_END"]) + nl
    return head + chunk * ((mb * 1024 * 1024) // len(chunk) + 1) + tail


