"""Разбор файла печати K2 без замирания программы (R-148, 16.10.2026).

ЗАЧЕМ. app/gcode_tool_slot.py читает из G-code строку выбора ячейки `T<n>` и служебные строки о
филаментах. Прежде каждый вызов резал на строки ВЕСЬ файл: на файле K2 в 30-60 МБ — секунды и
сотни мегабайт памяти на вызов, а запуск печати зовёт разбор трижды, два раза — из обработчика
веб-запроса. Интерфейс всей фермы на это время замирал. Теперь нужные строки ищутся регулярным
выражением прямо по байтам.

ЧТО ДОКАЗЫВАЕТ НАБОР (исполнением функций, без сервера, сети и принтеров):
  A. на синтетическом файле 60 МБ read_meta укладывается в 1 с и почти не тратит память
     (замер tracemalloc), find_tool_lines и смена ячейки — тоже быстро;
  B. результаты совпадают с прежним построчным разбором байт в байт: прежний разбор повторён здесь
     как эталон (_ref_lines — та же нарезка на строки, что была в модуле до 16.10.2026) и прогнан
     на тысячах случайных файлов с разными переводами строк, комментариями, похожими строками и
     строкой выбора в самом начале или в самом конце файла.

Запуск: python tools/test_gcode_tool_slot_perf.py   (0 = пройдено)
"""
