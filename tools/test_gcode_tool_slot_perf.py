# ── эталон: прежний построчный разбор (как он был в модуле до 16.10.2026) ──────────────────────
def _ref_lines(data):
    out = []
    if not isinstance(data, (bytes, bytearray)):
        return out
    data = bytes(data)
    pos, n = 0, len(data)
    while pos <= n:
        nl = data.find(b"\n", pos)
        end = n if nl < 0 else nl
        raw = data[pos:end]
        core = raw[:-1] if raw.endswith(b"\r") else raw
        out.append((pos, pos + len(core), core))
        if nl < 0:
            break
        pos = nl + 1
    return out


def _ref_find_tool_lines(data):
    out = []
    for i, (start, end, core) in enumerate(_ref_lines(data)):
        m = G._TOOL_RE.match(core)
        if m:
            out.append({"line": i + 1, "start": start, "end": end, "index": int(m.group(1)),
                        "text": core.decode("ascii", "replace")})
    return out


class _Ref(object):
    """Прежнее поведение целиком: те же функции модуля, но поиск строк — эталонный построчный.
    Подмена — только на время вызова и только внутри этого набора."""

    def __enter__(self):
        self._saved = (G.find_tool_lines, G._meta_lines)
        G.find_tool_lines, G._meta_lines = _ref_find_tool_lines, _ref_lines
        return self

    def __exit__(self, *a):
        G.find_tool_lines, G._meta_lines = self._saved


def both(fn, *args, **kw):
    new = fn(*args, **kw)
    with _Ref():
        old = fn(*args, **kw)
    return new, old


