import io
import json
import re
import threading
import time
import uuid
import zipfile

SCHEMA_VERSION = 1

# Терминальный статус принтера -> outcome_raw. IDLE из RUNNING ядро уже трактует как отмену
# (см. fail_project_print_job в handle_state) — события зеркалят ту же семантику.
TERMINAL_MAP = {"FINISH": "finished", "FAILED": "failed", "STOP": "cancelled", "IDLE": "cancelled"}


def _now():
    """Единый формат времени проекта (как CURRENT_TIMESTAMP в SQLite): UTC 'YYYY-MM-DD HH:MM:SS'."""
    return time.strftime("%Y-%m-%d %H:%M:%S", time.gmtime())


def _deep_copy(obj):
    """Глубокая копия payload'а через JSON (модуль-подписчик не может тронуть состояние ядра;
    заодно гарантирует JSON-сериализуемость: несериализуемое превращается в str)."""
    try:
        return json.loads(json.dumps(obj, ensure_ascii=False, default=str))
    except Exception:
        return {}


# ── Метаданные слайсера из УЖЕ доступного fdata (сырые байты .gcode/.3mf) ──
# Тот же подход, что обкатан в модуле склада (_inv_gcode_text): голова+хвост G-code,
# где Bambu/Orca/Prusa пишут комментарии-итоги. Не «глубокий парсер», а whitelist-выжимка.
_META_HEAD = 220 * 1024
_META_TAIL = 220 * 1024

def _gcode_text(fdata):
    try:
        raw = None
        if isinstance(fdata, (bytes, bytearray)) and bytes(fdata[:2]) == b"PK":
            with zipfile.ZipFile(io.BytesIO(fdata)) as z:
                gcs = [n for n in z.namelist() if n.lower().endswith(".gcode")]
                plates = [n for n in gcs if "plate_" in n.lower()] or gcs
                if not plates:
                    return ""
                raw = z.read(sorted(plates)[0])
        elif isinstance(fdata, (bytes, bytearray)):
            raw = bytes(fdata)
        if not raw:
            return ""
        chunk = raw if len(raw) <= (_META_HEAD + _META_TAIL) else (raw[:_META_HEAD] + b"\n" + raw[-_META_TAIL:])
        return chunk.decode("utf-8", "ignore")
    except Exception:
        return ""


def _hms_to_s(txt):
    """'1h 32m 10s' / '45m 2s' / '2d 1h' -> секунды."""
    s = 0
    for val, unit in re.findall(r"(\d+)\s*([dhms])", str(txt).lower()):
        s += int(val) * {"d": 86400, "h": 3600, "m": 60, "s": 1}[unit]
    return s or None

_META_PATTERNS = [
    ("slicer",          r";\s*generated by\s+([^\n;]+)"),
    ("profile_name",    r";\s*print_settings_id\s*[:=]\s*([^\n]+)"),
    ("layer_height",    r";\s*layer_height\s*[:=]\s*([0-9.]+)"),
    ("nozzle_diameter", r";\s*nozzle_diameter\s*[:=]\s*([0-9.,;]+)"),
    ("nozzle_temperature", r";\s*nozzle_temperature\s*[:=]\s*([0-9.,;]+)"),
    ("bed_temperature", r";\s*(?:bed_temperature|hot_plate_temp|textured_plate_temp|cool_plate_temp)\s*[:=]\s*([0-9.,;]+)"),
    ("filament_type",   r";\s*filament_type\s*[:=]\s*([^\n]+)"),
    ("plate_type",      r";\s*curr_bed_type\s*[:=]\s*([^\n]+)"),
    ("printer_model",   r";\s*printer_model\s*[:=]\s*([^\n]+)"),
]
_META_TIME_PATTERNS = [
    r";\s*total estimated time\s*[:=]\s*([^\n;]+)",
    r";\s*model printing time\s*[:=]\s*([^\n;]+)",
    r";\s*estimated printing time[^=\n]*=\s*([^\n]+)",
]
_META_WEIGHT_PATTERNS = [
    r"filament used \[g\]\s*[:=]\s*([0-9.,\s]+)",
    r"total filament weight \[g\]\s*[:=]\s*([0-9.,\s]+)",
]


# ── 16.10.2026 (R-136): плановые граммы ПО НОМЕРУ филамента ──
# Bambu Studio пишет в «; total filament weight [g] : …» только использованные филаменты, без нулей
# (GCodeProcessor.cpp), поэтому у проекта PLA, PETG, PLA, ABS с плитой из одного PETG там одно число —
# и по месту в строке оно доставалось филаменту №1. Надёжный вес по номеру — в Metadata/slice_info.config
# 3mf: <filament id="N" … used_g="…"> на каждую плиту (bbs_3mf.cpp). Плита — по правилу отправки на
# принтер: первая по sorted() среди Metadata/plate_N.gcode, иначе единственная описанная.
def _plate_filaments(fdata):
    """-> {"ids": [номера с 1], "used_g": {номер: г}} для отправляемой плиты, или None. Fail-open."""
    try:
        if not isinstance(fdata, (bytes, bytearray)) or bytes(fdata[:2]) != b"PK":
            return None
        import xml.etree.ElementTree as ET
        with zipfile.ZipFile(io.BytesIO(fdata)) as z:
            names = z.namelist()
            if "Metadata/slice_info.config" not in names:
                return None
            gcodes = [n for n in names if n.endswith(".gcode")]
            if not gcodes:
                return None
            plates = [n for n in gcodes if "plate_" in n.lower()]
            plate_no = None
            if plates:
                m = re.search(r"plate_(\d+)\.gcode$", sorted(plates)[0], re.IGNORECASE)
                plate_no = int(m.group(1)) if m else None
            raw = z.read("Metadata/slice_info.config")
        nodes = list(ET.fromstring(raw).iter("plate"))
        target = None
        for pl in nodes:
            num = None
            for md in pl.findall("metadata"):
                if (md.get("key") or "").strip().lower() == "index":
                    try:
                        num = int(str(md.get("value")).strip())
                    except Exception:
                        num = None
                    break
            if plate_no is not None and num == plate_no:
                target = pl
                break
        if target is None and plate_no is None and len(nodes) == 1:
            target = nodes[0]
        if target is None:
            return None
        ids, used = [], {}
        for fl in target.findall("filament"):
            try:
                fid = int(fl.get("id"))
            except Exception:
                continue
            #  16.10.2026 (R-136): номер больше 256 — повреждённый файл; такому описанию плиты не верим
            #  (список граммов длиной в этот номер занял бы сотни мегабайт и остановил запуск).
            if fid > 256:
                return None
            if fid < 1 or fid in ids:
                continue
            ids.append(fid)
            try:
                g = float(str(fl.get("used_g")).replace(",", "."))
            except Exception:
                continue
            if g == g and 0 <= g < 1e7:
                used[fid] = round(g, 2)
        return {"ids": sorted(ids), "used_g": used} if ids else None
    except Exception:
        return None


def _project_filament_count(fdata, text):
    """Сколько филаментов объявляет проект: project_settings.config 3mf, иначе шапка G-code. 0 — неизвестно."""
    n = 0
    try:
        if isinstance(fdata, (bytes, bytearray)) and bytes(fdata[:2]) == b"PK":
            with zipfile.ZipFile(io.BytesIO(fdata)) as z:
                if "Metadata/project_settings.config" in z.namelist():
                    cfg = json.loads(z.read("Metadata/project_settings.config").decode("utf-8", "ignore"))
                    for k in ("filament_type", "filament_colour", "filament_settings_id"):
                        v = cfg.get(k) if isinstance(cfg, dict) else None
                        if isinstance(v, list):
                            n = max(n, len(v))
    except Exception:
        pass
    for key in ("filament_type", "filament_colour", "filament_density"):
        m = re.search(r"(?m)^[ \t]*;[ \t]*" + key + r"[ \t]*[:=][ \t]*([^\r\n]*)$", text or "")
        if m:
            n = max(n, len([x for x in re.split(r"[;,]", m.group(1)) if x.strip()]))
    return n


def _weights_by_filament(fdata, text, header):
    """Плановые граммы по номеру филамента [w1, w2, …] или None (по номерам не разложить).
    header — список из шапки G-code в порядке строки. Источник 1 — slice_info плиты; затем шапка:
    «filament used [g]» (Orca/Prusa/Creality, с нулями) — как есть; шапка Bambu Studio без нулей —
    как есть, только если чисел столько же, сколько филаментов проекта (или проект неизвестен)."""
    pl = _plate_filaments(fdata)
    if pl and pl.get("used_g"):
        out = [0.0] * max(pl["ids"])
        for fid, g in pl["used_g"].items():
            out[fid - 1] = g
        return out
    if not header:
        return None
    if re.search(r"(?m)^[ \t]*;[ \t]*filament used \[g\][ \t]*[:=]", text or ""):
        return header
    if not re.search(r"total filament weight \[g\][ \t]*[:=]", text or "", re.IGNORECASE):
        return header
    n_proj = _project_filament_count(fdata, text)
    if n_proj and len(header) < n_proj:
        if pl and len(pl["ids"]) == len(header):
            out = [0.0] * max(pl["ids"])
            for fid, g in zip(pl["ids"], header):     # Studio пишет числа по возрастанию номера
                out[fid - 1] = g
            return out
        return None
    return header

def extract_profile_meta(fdata):
    """Компактный snapshot профиля из fdata. Отсутствующие поля просто не пишутся (NULL-семантика)."""
    text = _gcode_text(fdata)
    if not text:
        return {}
    meta = {}
    for key, pat in _META_PATTERNS:
        m = re.search(pat, text, re.IGNORECASE)
        if m:
            meta[key] = m.group(1).strip().strip(";").strip()
    for pat in _META_TIME_PATTERNS:
        m = re.search(pat, text, re.IGNORECASE)
        if m:
            sec = _hms_to_s(m.group(1))
            if sec:
                meta["estimated_s"] = sec
                break
    header = []
    for pat in _META_WEIGHT_PATTERNS:
        m = re.search(pat, text, re.IGNORECASE)
        if m:
            try:
                wlist = [round(float(x.replace(",", ".")), 2)
                         for x in re.split(r"[\s,]+", m.group(1).strip()) if x]
            except Exception:
                wlist = []
            if wlist:
                header = wlist
                break
    # planned_weights_g — ПО НОМЕРУ ФИЛАМЕНТА (0 у неиспользуемых), нужен для точной привязки веса к
    # назначенному слоту; planned_weight_g — общий вес (контекст). 16.10.2026 (R-136): сперва slice_info
    # плиты; шапку Bambu Studio без нулей по номерам не раскладываем — тогда только общий вес.
    by_id = _weights_by_filament(fdata, text, header)
    if by_id:
        meta["planned_weights_g"] = by_id
    wtot = by_id or header
    if wtot:
        total = round(sum(wtot), 2)
        if total > 0:
            meta["planned_weight_g"] = total
    if "slicer" in meta:
        parts = meta["slicer"].split()
        if len(parts) >= 2 and re.match(r"^[\d.]+", parts[-1]):
            meta["slicer_version"] = parts[-1]
            meta["slicer"] = " ".join(parts[:-1])
    return meta


def build_assignments(ams_map, weights, external, ext_slot=-1):
    """Generic-назначение материала задания: [{filament_index, ams_slot, external, planned_g}].
    ams_map — реальный список, отправленный на принтер: индекс = номер филамента файла, значение =
    назначенный AMS-слот (для явного выбора — [slot]; авто-Bambu — range(N); Klipper/FF — [0];
    не-AMS Bambu — []). weights — плановый вес по индексу филамента (или []). ИНВАРИАНТ: whitelist
    только позиционных/весовых полей — НИКАКИХ token/serial/spool/vendor. Если веса известны, берём
    ТОЛЬКО реально печатаемые филаменты (>0 г) — так задание с 4 катушками в AMS, но одним филаментом,
    даёт одну позицию, а не четыре.

    16.10.2026 (R-137): ext_slot — какая внешняя катушка: -1 основная (правая), -2 левая у H2D
    (Bambu 254). Внешняя печать без единого слота >= 0 в карте (пустая, [-1], [-2], [-1,-1,…]) даёт
    одну позицию ams_slot=ext_slot; номер филамента — первый с весом > 0 (у плиты из проекта на
    несколько материалов это не обязательно №1)."""
    out = []
    weights = weights or []
    have_w = bool(weights)
    _slots = []
    for x in (ams_map or []):
        try:
            _slots.append(int(x))
        except Exception:
            _slots.append(None)
    if external and not any(s is not None and s >= 0 for s in _slots):
        try:
            es = int(ext_slot)
        except Exception:
            es = -1
        if es not in (-1, -2):
            es = -1
        if es == -1 and -2 in _slots:
            es = -2                            # карта [-2] сама говорит: левая внешняя
        if not have_w:
            return [{"filament_index": 0, "ams_slot": es, "external": True, "planned_g": None}]
        for i, pg in enumerate(weights):
            try:
                pg = float(pg)
            except Exception:
                continue
            if pg > 0:
                return [{"filament_index": i, "ams_slot": es, "external": True, "planned_g": pg}]
        return []
    if ams_map:
        for i, slot in enumerate(ams_map):
            try:
                s = int(slot)
            except Exception:
                continue
            if s < 0:
                continue
            pg = weights[i] if i < len(weights) else None
            if have_w and (pg is None or pg <= 0):
                continue                       # филамент определён в проекте, но НЕ печатается (0 г)
            out.append({"filament_index": i, "ams_slot": s, "external": bool(external),
                        "planned_g": (pg if (pg is not None and pg > 0) else None)})
    return out


class PrintRunEvents:
    """Источник событий печати. Хранит ТОЛЬКО временную in-memory карту активных событий;
    printer_info_fn(pid) -> dict|None (белый список полей принтера, БЕЗ token/serial/ip);
    hook_fire(name, payload) — извещение подписчиков (сбои подписчиков глотает вызывающий)."""

    def __init__(self, log=None, printer_info_fn=None, hook_fire=None):
        self.log = log
        self.printer_info_fn = printer_info_fn
        self.hook_fire = hook_fire
        self._mem = threading.Lock()          # защита _active/_dispatch (handle_state зовут разные воркеры)
        self._active = {}                     # pid -> {"run_id","file_norm","started_mono","payload"}
        self._dispatch = {}                   # pid -> {"fname","meta","ts"} — из _send_file_to_printer

    def _log(self, msg):
        try:
            if self.log:
                self.log.debug("[RUN-EVENTS] " + msg)
        except Exception:
            pass

    def _fire(self, name, payload):
        """Испустить событие. Копия payload'а глубокая: подписчик не может изменить состояние ядра.
        Ошибка самого hook_fire тоже глотается — события не влияют на печать."""
        try:
            if self.hook_fire:
                self.hook_fire(name, _deep_copy(payload))
        except Exception as e:
            self._log("hook_fire failed: %s" % e)

    # ── метаданные при отправке файла (единая точка _send_file_to_printer) ──
    def stash_dispatch(self, pid, fname, fdata):
        try:
            self._dispatch[pid] = {"fname": str(fname or ""), "meta": extract_profile_meta(fdata), "ts": time.time()}
        except Exception as e:
            self._log("stash_dispatch failed: %s" % e)

    def stash_assignments(self, pid, ams_map, fdata=None, external=False, ext_slot=-1):
        """Сохраняет ФАКТИЧЕСКОЕ назначение материала задания (из _send_file_to_printer), чтобы включить
        его в следующий print_run_started. Так подписчик (модуль качества) сопоставляет материалы ТОЛЬКО
        с реально назначенными позициями, а не со всеми катушками AMS. Fail-open.
        ext_slot (16.10.2026, R-137) — внешняя катушка печати: -1 основная, -2 левая у H2D."""
        try:
            d = self._dispatch.get(pid) or {}
            weights = (d.get("meta") or {}).get("planned_weights_g")
            if weights is None and fdata is not None:
                weights = extract_profile_meta(fdata).get("planned_weights_g")
            d["assignments"] = build_assignments(list(ams_map or []), weights, external, ext_slot=ext_slot)
            d.setdefault("ts", time.time())
            self._dispatch[pid] = d
        except Exception as e:
            self._log("stash_assignments failed: %s" % e)

    def _take_dispatch(self, pid):
        d = self._dispatch.pop(pid, None)
        if d and (time.time() - d.get("ts", 0)) < 3600:   # метаданные валидны в пределах часа после отправки
            return d
        return {}

    # ── старт печати ──
    def on_start(self, pid, ctx):
        """Вызывается ядром на переходе в PREPARE/RUNNING (правила автомата handle_state).
        Возвращает run_id или None. Повторные PREPARE/RUNNING того же задания события НЕ дублируют;
        смена файла без терминального статуса закрывает старое событие unknown/superseded."""
        try:
            return self._on_start(pid, dict(ctx or {}))
        except Exception as e:
            self._log("on_start failed: %s" % e)
            return None

    def _on_start(self, pid, ctx):
        fn = str(ctx.get("file_norm") or "")
        with self._mem:
            act = self._active.get(pid)
        if act and act.get("file_norm") == fn:
            return act["run_id"]                          # то же задание — событие уже было
        if act:                                           # сменился файл без терминала — честно закрываем старое
            self._finish_active(pid, act, "unknown", "superseded_by_new_job", None)
        run_id = "run_" + uuid.uuid4().hex
        now = _now()
        pinfo = {}
        try:
            pinfo = dict(self.printer_info_fn(pid) or {}) if self.printer_info_fn else {}
        except Exception:
            pinfo = {}
        pstate = dict(ctx.get("pstate") or {})
        printer_snap = {k: pinfo.get(k) for k in ("name", "type", "model", "gen") if pinfo.get(k) not in (None, "")}
        if pstate.get("nozzle_count"):
            printer_snap["nozzle_count"] = pstate.get("nozzle_count")
        printer_snap["has_ams"] = bool(pstate.get("ams_trays"))
        disp = self._take_dispatch(pid)
        meta = disp.get("meta") or {}
        assignments = disp.get("assignments") or []
        payload = {
            "run_id": run_id, "source": str(ctx.get("source") or "unknown"),
            "printer_id": pid, "printer_name": pinfo.get("name"), "printer_type": pinfo.get("type"),
            "printer_model": pinfo.get("model"),
            "project_id": ctx.get("project_id"), "task_id": ctx.get("task_id"), "file_id": ctx.get("file_id"),
            "filename": ctx.get("filename"), "file_norm": fn or None, "file_hash": ctx.get("file_hash"),
            "batch_id": ctx.get("batch_id"), "queue_id": ctx.get("queue_id"),
            "started_at": now, "finished_at": None, "elapsed_s": None,
            "estimated_s": meta.get("estimated_s"), "final_percent": None,
            "outcome_raw": "running", "terminal_reason": None,
            "source_payload": {k: ctx.get(k) for k in ("src_raw", "flow", "pjob_id", "server_sent", "staging_file")
                               if ctx.get(k) not in (None, "")},
            "profile_snapshot": meta, "printer_snapshot": printer_snap,
            # material_assignments — фактические позиции материала ЭТОГО задания (из отправки), НЕ «все катушки AMS».
            # Пусто → назначение неизвестно (печать с экрана/reprint) → подписчик материалы НЕ пишет.
            "material_assignments": assignments,
            "origin": "live", "schema_version": SCHEMA_VERSION,
        }
        with self._mem:
            self._active[pid] = {"run_id": run_id, "file_norm": fn, "started_mono": time.monotonic(), "payload": payload}
        self._fire("print_run_started", payload)
        return run_id

    # ── терминальный исход ──
    def on_terminal(self, pid, state, pstate=None):
        """FINISH/FAILED/STOP/IDLE (PAUSED игнорируется). finished-событие испускается РОВНО один раз
        на активное событие; терминал без активного события — no-op (фантомы не создаются)."""
        try:
            if str(state) == "PAUSED":
                return None
            with self._mem:
                act = self._active.pop(pid, None)
            if not act:
                return None
            outcome = TERMINAL_MAP.get(str(state), "unknown")
            pct = None
            try:
                pct = float((pstate or {}).get("percent"))
            except Exception:
                pct = None
            return self._finish_active(pid, act, outcome, "printer_state:" + str(state), pct)
        except Exception as e:
            self._log("on_terminal failed: %s" % e)
            return None

    def _finish_active(self, pid, act, outcome, reason, final_percent):
        payload = dict(act.get("payload") or {})
        started_mono = act.get("started_mono")
        payload["outcome_raw"] = outcome
        payload["terminal_reason"] = reason
        payload["finished_at"] = _now()
        payload["elapsed_s"] = int(time.monotonic() - started_mono) if started_mono else None
        payload["final_percent"] = final_percent
        with self._mem:                                    # снята с активных (если ещё числится)
            if self._active.get(pid, {}).get("run_id") == payload.get("run_id"):
                self._active.pop(pid, None)
        self._fire("print_run_finished", payload)
        return outcome
